# ============================================================
# 13. PREDICTION FUNCTION
# ============================================================

def predict(X, weights, bias):

    return np.dot(X, weights) + bias


# ============================================================
# 14. LOSS FUNCTION
# ============================================================

def calculate_mse(y_actual, y_predicted):

    error = y_actual - y_predicted

    mse = np.mean(error ** 2)

    return mse


# ============================================================
# 15. GRADIENT CALCULATION
# ============================================================

def calculate_gradient(X, y_actual, y_predicted):

    number_of_samples = X.shape[0]

    error = y_predicted - y_actual

    # Derivative with respect to weights
    dw = (
        2 / number_of_samples
    ) * np.dot(X.T, error)

    # Derivative with respect to bias
    db = 2 * np.mean(error)

    return dw, db


# ============================================================
# 16. UPDATE PARAMETERS
# ============================================================

def update_parameters(
    weights,
    bias,
    dw,
    db,
    learning_rate
):

    weights = weights - learning_rate * dw

    bias = bias - learning_rate * db

    return weights, bias


# ============================================================
# 17. TRAIN LINEAR REGRESSION FROM SCRATCH
# ============================================================

print("\n12. TRAINING NUMPY LINEAR REGRESSION")

# Standardize target using training data only
y_mean = np.mean(y_train)

y_std = np.std(y_train)

y_train_scaled = (
    y_train - y_mean
) / y_std

# Initialize parameters
weights, bias = initialize_parameters(
    number_of_features
)

learning_rate = 0.05

epochs = 1000

loss_history = []

for epoch in range(epochs):

    # Forward propagation
    predictions = predict(
        X_train_scaled,
        weights,
        bias
    )

    # Calculate loss
    loss = calculate_mse(
        y_train_scaled,
        predictions
    )

    loss_history.append(loss)

    # Calculate gradients
    dw, db = calculate_gradient(
        X_train_scaled,
        y_train_scaled,
        predictions
    )

    # Update weights and bias
    weights, bias = update_parameters(
        weights,
        bias,
        dw,
        db,
        learning_rate
    )

    if (epoch + 1) % 100 == 0:

        print(
            f"Epoch {epoch + 1}/{epochs} "
            f"| MSE: {loss:.6f}"
        )


print("\nNUMPY MODEL TRAINING COMPLETED!")

