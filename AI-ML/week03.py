print("""
Linear Regression Equation:

y_predicted = XW + b

Where:

X = Input feature matrix
W = Model weights
b = Bias
y = Actual target
y_predicted = Predicted target

Mean Squared Error:

MSE = (1/n) * SUM((y - y_predicted)^2)

Gradient Descent:

W_new = W_old - learning_rate * dW

b_new = b_old - learning_rate * db
""")


# ============================================================
# 12. INITIALIZE MODEL PARAMETERS
# ============================================================

print("\n11. INITIALIZING PARAMETERS")

number_of_features = X_train_scaled.shape[1]

def initialize_parameters(number_of_features):

    weights = np.zeros(number_of_features)

    bias = 0.0

    return weights, bias


weights, bias = initialize_parameters(
    number_of_features
)

print("Initial Weights:")
print(weights)

print("Initial Bias:")
