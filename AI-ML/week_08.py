"""### Step 3: Creating Embeddings with Sentence Transformers
We will use the highly efficient `'all-MiniLM-L6-v2'` model to transform our text documents into dense numerical vectors of size 384.
"""

from sentence_transformers import SentenceTransformer
import numpy as np

# Initialize the sentence transformer model
model = SentenceTransformer('all-MiniLM-L6-v2')

# Encode all documents into high-dimensional vectors
doc_embeddings = model.encode(documents, convert_to_numpy=True)

print(f"Embedding Matrix Shape: {doc_embeddings.shape}")
# The shape is (35, 384), representing 35 documents encoded into 384-dimensional vectors.

"""### Step 4: Semantic Search Engine Implementation & Mathematics Behind It

To build our search function without complex libraries, we write a custom retriever using NumPy. Here is the detailed breakdown of the concepts and mathematical formulas involved:

#### 1. Encoding the Query
When a query string is entered (e.g., *"cooking tips"*), we must map it into the exact same vector space as our documents. We use our pre-trained transformer model to generate a query vector $\vec{q}$ of size $1 \times 384$:
$$\vec{q} = \text{model.encode}(q)$$

#### 2. Vector Dot Product
The dot product of our document matrix $D$ (where each row $d_i$ represents a document embedding vector) and the query vector $\vec{q}$ calculates the directional alignment:
$$\text{dot\_products}_i = \vec{d}_i \cdot \vec{q} = \sum_{j=1}^{n} d_{i,j} q_j$$
In NumPy, this matrix-vector multiplication is computed efficiently using `np.dot(doc_embeddings, query_embedding)`.

#### 3. Vector Norms (Magnitude)
To prevent longer documents or larger overall vector scales from biasing the search results, we must normalize the scores. We compute the L2 norm (Euclidean length) of each document vector $\vec{d}_i$ and our query vector $\vec{q}$:
$$\|\vec{d}_i\| = \sqrt{\sum_{j=1}^{n} d_{i,j}^2}, \quad \|\vec{q}\| = \sqrt{\sum_{j=1}^{n} q_j^2}$$
These are implemented using `np.linalg.norm`.

#### 4. Cosine Similarity Formula
Cosine similarity measures the cosine of the angle $\theta$ between the document vector and the query vector. It outputs a score between $-1$ and $1$, where $1$ indicates identical directions (maximum semantic similarity):
$$\text{Similarity}_i = \cos(\theta) = \frac{\vec{d}_i \cdot \vec{q}}{\|\vec{d}_i\| \|\vec{q}\|}$$

#### 5. Ranking
Finally, we sort the similarity scores in descending order using `np.argsort(similarities)[::-1]` and extract the top $k$ documents that match closest to our query.
"""

def semantic_search(query, top_k=3):
    # Encode the input query
    query_embedding = model.encode(query, convert_to_numpy=True)

    # Compute cosine similarity manually using NumPy
    # Cosine Similarity = (A . B) / (||A|| * ||B||)
    dot_products = np.dot(doc_embeddings, query_embedding)
    doc_norms = np.linalg.norm(doc_embeddings, axis=1)
    query_norm = np.linalg.norm(query_embedding)

    similarities = dot_products / (doc_norms * query_norm)

    # Get indices sorted by similarity score descending
    sorted_indices = np.argsort(similarities)[::-1]

    # Return top_k results
    results = []
    for idx in sorted_indices[:top_k]:
        results.append({
            "document": documents[idx],
            "similarity": float(similarities[idx]),
            "index": int(idx)
        })
    return results

# Quick test
