# 1. IMPORT LIBRARIES
import random
import csv
import re
import os
import matplotlib.pyplot as plt

from datetime import datetime, timedelta
from collections import Counter, defaultdict

# ============================================================
# 2. GENERATE SAMPLE LOG DATASET
# ============================================================

random.seed(42)

log_levels = ["INFO", "WARNING", "ERROR", "CRITICAL"]

messages = {
    "INFO": [
        "Application started",
        "User logged in",
        "Database connection successful",
        "Request processed successfully"
    ],
    "WARNING": [
        "High memory usage",
        "Slow API response",
        "Disk space running low"
    ],
    "ERROR": [
        "Database connection failed",
        "API request failed",
        "Invalid user credentials",
        "File not found"
    ],
    "CRITICAL": [
        "Application crashed",
        "Database unavailable",
        "System resource exhausted"
    ]
}

start_time = datetime(2026, 1, 1, 8, 0, 0)

logs = []

for i in range(200):
    timestamp = start_time + timedelta(
        minutes=random.randint(0, 10000)
    )

    level = random.choices(
        log_levels,
        weights=[50, 20, 25, 5]
    )[0]

    message = random.choice(messages[level])

    logs.append(
        f"{timestamp} | {level} | {message}"
    )

# Add invalid records for testing
logs.extend([
    "INVALID LOG ENTRY",
    "2026-01-01 10:00:00 | UNKNOWN | Unexpected level"
])

with open("application.log", "w") as file:
    file.write("\n".join(logs))

print("Sample log file created successfully!")

# ============================================================
# 3. READ LOG FILE
# ============================================================

def read_logs(file_path):

    if not os.path.exists(file_path):
        raise FileNotFoundError(
            "Log file does not exist"
        )

    with open(file_path, "r") as file:
        records = file.readlines()

    if not records:
        print("Log file is empty")

    return records


raw_logs = read_logs("application.log")

print("\nTotal log entries:", len(raw_logs))

# ============================================================
# 4. PARSE LOG ENTRIES
# ============================================================

def parse_log(line):

    pattern = (
        r"(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2})"
        r"\s*\|\s*(INFO|WARNING|ERROR|CRITICAL)"
        r"\s*\|\s*(.*)"
    )

    match = re.match(pattern, line.strip())

    if not match:
        return None

    timestamp, level, message = match.groups()

    try:
        timestamp = datetime.strptime(
            timestamp,
            "%Y-%m-%d %H:%M:%S"
        )
    except ValueError:
        return None

    return {
        "timestamp": timestamp,
        "level": level,
        "message": message
    }


parsed_logs = []
invalid_logs = []

for line in raw_logs:

    record = parse_log(line)

    if record:
        parsed_logs.append(record)
    else:
        invalid_logs.append(line.strip())


print("Valid records:", len(parsed_logs))
print("Invalid records:", len(invalid_logs))

# ============================================================
# 5. ANALYZE LOG LEVELS
# ============================================================

def count_log_levels(records):

    counts = Counter(
        record["level"]
        for record in records
    )

    return counts


level_counts = count_log_levels(parsed_logs)

print("\nLOG LEVEL DISTRIBUTION")

for level, count in level_counts.items():
    print(f"{level}: {count}")

# ============================================================
# 6. IDENTIFY FREQUENT ERRORS
# ============================================================

def get_error_summary(records):

    errors = [
        record["message"]
        for record in records
        if record["level"] in ["ERROR", "CRITICAL"]
    ]

    return Counter(errors)


error_summary = get_error_summary(parsed_logs)

print("\nMOST FREQUENT ERRORS")

for error, count in error_summary.most_common():
    print(f"{error}: {count}")

# ============================================================
# 7. IDENTIFY PEAK ERROR HOUR
# ============================================================

def errors_by_hour(records):

    hourly_errors = defaultdict(int)

    for record in records:

        if record["level"] in ["ERROR", "CRITICAL"]:

            hour = record["timestamp"].hour

            hourly_errors[hour] += 1

    return hourly_errors


hourly_summary = errors_by_hour(parsed_logs)

if hourly_summary:

    peak_hour = max(
        hourly_summary,
        key=hourly_summary.get
    )

    print("\nPEAK ERROR HOUR:", peak_hour)

    print(
        "Number of errors:",
        hourly_summary[peak_hour]
    )

else:
    print("\nNo errors found")

# ============================================================
# 8. CALCULATE ERROR PERCENTAGE
# ============================================================

def calculate_error_percentage(records):

    if not records:
        return 0

    errors = sum(
        1 for record in records
        if record["level"] in ["ERROR", "CRITICAL"]
    )

    return (errors / len(records)) * 100


error_percentage = calculate_error_percentage(
    parsed_logs
)

print(
    f"\nError Percentage: {error_percentage:.2f}%"
)

# ============================================================
# 9. EXPORT ERROR RECORDS TO CSV
# ============================================================

def export_errors(records, output_file):

    errors = [
        record for record in records
        if record["level"] in ["ERROR", "CRITICAL"]
    ]

    with open(
        output_file,
        "w",
        newline=""
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=[
                "timestamp",
                "level",
                "message"
            ]
        )

        writer.writeheader()

        for record in errors:

            writer.writerow({
                "timestamp": record["timestamp"],
                "level": record["level"],
                "message": record["message"]
            })


export_errors(
    parsed_logs,
    "error_report.csv"
)

print("\nError report exported successfully!")

# ============================================================
# 10. EXPORT SUMMARY REPORT
# ============================================================

def export_summary(records, output_file):

    counts = count_log_levels(records)

    total = len(records)

    with open(
        output_file,
        "w",
        newline=""
    ) as file:

        writer = csv.writer(file)

        writer.writerow(["Metric", "Value"])

        writer.writerow(["Total Logs", total])

        for level in [
            "INFO",
            "WARNING",
            "ERROR",
            "CRITICAL"
        ]:

            writer.writerow([
                f"{level} Count",
                counts.get(level, 0)
            ])

        writer.writerow([
            "Error Percentage",
            round(
                calculate_error_percentage(records),
                2
            )
        ])

        writer.writerow([
            "Invalid Log Entries",
            len(invalid_logs)
        ])


export_summary(
    parsed_logs,
    "summary_report.csv"
)

print("Summary report exported successfully!")

