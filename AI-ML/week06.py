import os
import zipfile
import urllib.request
import warnings
import joblib
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score
from sklearn.decomposition import PCA
from sklearn.ensemble import IsolationForest

warnings.filterwarnings("ignore")
sns.set_theme(style="whitegrid")

RANDOM_STATE = 42
OUTPUT_DIR = "/content/week6_outputs"
os.makedirs(OUTPUT_DIR, exist_ok=True)

# ------------------------------------------------
# 1. DOWNLOAD AND LOAD UCI ONLINE RETAIL DATASET
# ------------------------------------------------

DATA_URL = "https://archive.ics.uci.edu/static/public/352/online+retail.zip"
ZIP_PATH = "/content/online_retail.zip"

print("Downloading UCI Online Retail dataset...")

urllib.request.urlretrieve(DATA_URL, ZIP_PATH)

with zipfile.ZipFile(ZIP_PATH, "r") as archive:
    excel_files = [
        name for name in archive.namelist()
        if name.lower().endswith(".xlsx")
    ]

    if not excel_files:
        raise FileNotFoundError("Excel dataset not found inside downloaded ZIP.")

    excel_file = excel_files[0]
    with archive.open(excel_file) as file:
        df = pd.read_excel(file)

print("\nDataset downloaded successfully!")
print("Original dataset shape:", df.shape)
display(df.head())

# ------------------------------------------------
# 2. UNDERSTAND THE DATA
# ------------------------------------------------

print("\nDataset information:")
df.info()

print("\nStatistical summary:")
display(df.describe(include="all").T)

print("\nMissing values:")
print(df.isnull().sum().sort_values(ascending=False))

# ------------------------------------------------
# 3. DATA CLEANING
# ------------------------------------------------

df.columns = df.columns.str.strip()

# Remove rows without customer IDs
df = df.dropna(subset=["CustomerID"]).copy()

# Remove duplicate records
df = df.drop_duplicates().copy()

# Remove cancelled invoices (invoice numbers starting with C)
df["InvoiceNo"] = df["InvoiceNo"].astype(str)
df = df[~df["InvoiceNo"].str.startswith("C")].copy()

# Convert fields to correct data types
df["Quantity"] = pd.to_numeric(df["Quantity"], errors="coerce")
df["UnitPrice"] = pd.to_numeric(df["UnitPrice"], errors="coerce")
df["InvoiceDate"] = pd.to_datetime(
    df["InvoiceDate"], errors="coerce"
)

# Remove invalid quantities and prices
df = df.dropna(
    subset=["Quantity", "UnitPrice", "InvoiceDate"]
).copy()

df = df[
    (df["Quantity"] > 0) &
    (df["UnitPrice"] > 0)
].copy()

# Create transaction amount
df["TotalPrice"] = df["Quantity"] * df["UnitPrice"]

# Convert customer IDs to string
df["CustomerID"] = df["CustomerID"].astype(int).astype(str)

print("\nCleaned dataset shape:", df.shape)
print("Unique customers:", df["CustomerID"].nunique())
print("Unique invoices:", df["InvoiceNo"].nunique())

# ------------------------------------------------
# 4. EXPLORATORY DATA ANALYSIS
# ------------------------------------------------

print("\nTop 10 countries by transaction count:")
display(
    df["Country"].value_counts().head(10).reset_index()
    .rename(columns={"index": "Country", "count": "Transactions"})
)

country_sales = (
    df.groupby("Country")["TotalPrice"]
    .sum()
    .sort_values(ascending=False)
    .head(10)
)

plt.figure(figsize=(11, 5))
country_sales.sort_values().plot(kind="barh")
plt.title("Top 10 Countries by Sales")
plt.xlabel("Total Sales")
plt.ylabel("Country")
plt.tight_layout()
plt.show()

monthly_sales = (
    df.set_index("InvoiceDate")["TotalPrice"]
    .resample("ME")
    .sum()
)

plt.figure(figsize=(12, 5))
monthly_sales.plot()
plt.title("Monthly Sales Trend")
plt.xlabel("Month")
plt.ylabel("Sales")
plt.tight_layout()
plt.show()

# ------------------------------------------------
# 5. BUILD CUSTOMER-LEVEL RFM FEATURES
# ------------------------------------------------

# Reference date: one day after the last transaction
reference_date = df["InvoiceDate"].max() + pd.Timedelta(days=1)

rfm = df.groupby("CustomerID").agg(
    Recency=("InvoiceDate", lambda x:
             (reference_date - x.max()).days),
    Frequency=("InvoiceNo", "nunique"),
    Monetary=("TotalPrice", "sum")
).reset_index()

print("\nRFM customer dataset:")
display(rfm.head())

print("\nRFM statistics:")
display(rfm[["Recency", "Frequency", "Monetary"]].describe())

print("Number of customers:", len(rfm))

# ------------------------------------------------
# 6. HANDLE SKEWNESS AND OUTLIERS
# ------------------------------------------------

# RFM values are usually right-skewed.
# log1p reduces skewness while retaining zero values.

rfm_features = ["Recency", "Frequency", "Monetary"]

rfm_model = rfm[rfm_features].copy()

rfm_log = np.log1p(rfm_model)

print("\nSkewness before transformation:")
print(rfm_model.skew())

print("\nSkewness after log transformation:")
print(rfm_log.skew())

# ------------------------------------------------
# 7. STANDARDIZE RFM FEATURES
# ------------------------------------------------

scaler = StandardScaler()

X_scaled = scaler.fit_transform(rfm_log)

print("\nScaled feature shape:", X_scaled.shape)

# ------------------------------------------------
# 8. FIND OPTIMAL NUMBER OF CLUSTERS
# ELBOW METHOD + SILHOUETTE SCORE
# ------------------------------------------------

# Silhouette calculation on a sample keeps execution practical.
rng = np.random.RandomState(RANDOM_STATE)
sample_size = min(10000, len(X_scaled))
sample_indices = rng.choice(
    len(X_scaled), size=sample_size, replace=False
)
X_sample = X_scaled[sample_indices]

k_values = range(2, 7)
inertia_values = []
silhouette_values = []

print("\nTesting different K values...")

for k in k_values:
    kmeans_temp = KMeans(
        n_clusters=k,
        random_state=RANDOM_STATE,
        n_init=10
    )

    sample_labels = kmeans_temp.fit_predict(X_sample)

    inertia_values.append(kmeans_temp.inertia_)
    silhouette_values.append(
        silhouette_score(X_sample, sample_labels)
    )

    print(
        f"K={k} | Inertia={kmeans_temp.inertia_:.2f} "
        f"| Silhouette={silhouette_values[-1]:.4f}"
    )

# Elbow plot
plt.figure(figsize=(8, 5))
plt.plot(list(k_values), inertia_values, marker="o")
plt.xlabel("Number of Clusters (K)")
plt.ylabel("Inertia")
plt.title("Elbow Method")
plt.xticks(list(k_values))
plt.show()

# Silhouette plot
plt.figure(figsize=(8, 5))
plt.plot(list(k_values), silhouette_values, marker="o")
plt.xlabel("Number of Clusters (K)")
plt.ylabel("Silhouette Score")
plt.title("Silhouette Score for Different K Values")
plt.xticks(list(k_values))
plt.show()

# Select K using highest silhouette score
best_k = list(k_values)[int(np.argmax(silhouette_values))]

print("\nSelected number of clusters:", best_k)

# ------------------------------------------------
# 9. TRAIN FINAL K-MEANS MODEL
# ------------------------------------------------

kmeans = KMeans(
    n_clusters=best_k,
    random_state=RANDOM_STATE,
    n_init=10
)

rfm["Cluster"] = kmeans.fit_predict(X_scaled)

print("\nCustomer cluster counts:")
display(
    rfm["Cluster"].value_counts()
    .sort_index()
    .rename("Customer Count")
    .reset_index()
)

# ------------------------------------------------
# 10. CLUSTER PROFILING
# ------------------------------------------------

cluster_profile = rfm.groupby("Cluster").agg(
    Customer_Count=("CustomerID", "count"),
    Average_Recency=("Recency", "mean"),
    Average_Frequency=("Frequency", "mean"),
    Average_Monetary=("Monetary", "mean"),
    Median_Recency=("Recency", "median"),
    Median_Frequency=("Frequency", "median"),
    Median_Monetary=("Monetary", "median")
).round(2)

cluster_profile["Customer_Percentage"] = (
    cluster_profile["Customer_Count"] / len(rfm) * 100
).round(2)

print("\nCLUSTER PROFILES")
display(cluster_profile)

# ------------------------------------------------
# 11. AUTOMATIC CUSTOMER SEGMENT INTERPRETATION
# ------------------------------------------------

# These labels are heuristic descriptions based on each
# cluster's actual RFM profile, not predefined target labels.

overall_monetary = rfm["Monetary"].median()
overall_frequency = rfm["Frequency"].median()
overall_recency = rfm["Recency"].median()

def interpret_cluster(row):
    recent = row["Average_Recency"] <= overall_recency
    frequent = row["Average_Frequency"] >= overall_frequency
    high_value = row["Average_Monetary"] >= overall_monetary

    if recent and frequent and high_value:
        return "High-value loyal customers"
    elif recent and frequent:
        return "Active regular customers"
    elif high_value:
        return "High-spending customers"
    elif not recent and not frequent:
        return "At-risk / inactive customers"
    elif frequent:
        return "Regular customers"
    else:
        return "Occasional customers"

cluster_profile["Segment_Interpretation"] = (
    cluster_profile.apply(interpret_cluster, axis=1)
)

print("\nCUSTOMER SEGMENT INTERPRETATION")
display(cluster_profile)

# ------------------------------------------------
# 12. VISUALIZE CUSTOMER SEGMENTS
# ------------------------------------------------

plt.figure(figsize=(10, 6))

sns.scatterplot(
    data=rfm,
    x="Recency",
    y="Monetary",
    hue="Cluster",
    palette="tab10",
    alpha=0.65
)

plt.title("Customer Segments: Recency vs Monetary")
plt.xlabel("Recency (Days)")
plt.ylabel("Monetary Value")
plt.tight_layout()
plt.show()

# Cluster feature comparison
profile_for_plot = cluster_profile[
    ["Average_Recency", "Average_Frequency", "Average_Monetary"]
]

profile_normalized = (
    profile_for_plot - profile_for_plot.min()
) / (
    profile_for_plot.max() - profile_for_plot.min() + 1e-9
)

plt.figure(figsize=(10, 6))
sns.heatmap(
    profile_normalized,
    annot=True,
    cmap="YlGnBu",
    fmt=".2f"
)
plt.title("Normalized Customer Cluster Profiles")
plt.tight_layout()
plt.show()

# ------------------------------------------------
# 13. DIMENSIONALITY REDUCTION USING PCA
# ------------------------------------------------

pca = PCA(n_components=2, random_state=RANDOM_STATE)

X_pca = pca.fit_transform(X_scaled)

pca_df = pd.DataFrame({
    "PCA1": X_pca[:, 0],
    "PCA2": X_pca[:, 1],
    "Cluster": rfm["Cluster"].astype(str).values
})

print("\nPCA explained variance:")
print("Component 1:", round(pca.explained_variance_ratio_[0], 4))
print("Component 2:", round(pca.explained_variance_ratio_[1], 4))
print(
    "Total explained variance:",
    round(pca.explained_variance_ratio_.sum(), 4)
)

plt.figure(figsize=(10, 7))
sns.scatterplot(
    data=pca_df,
    x="PCA1",
    y="PCA2",
    hue="Cluster",
    palette="tab10",
    alpha=0.65,
    s=35
)
plt.title("Customer Clusters Visualized Using PCA")
plt.xlabel("Principal Component 1")
plt.ylabel("Principal Component 2")
plt.tight_layout()
plt.show()

# ------------------------------------------------
# 14. ANOMALY DETECTION USING ISOLATION FOREST
# ------------------------------------------------

# Isolation Forest identifies unusual RFM combinations.
# contamination=0.03 estimates approximately 3% anomalies.

isolation_forest = IsolationForest(
    n_estimators=200,
    contamination=0.03,
    random_state=RANDOM_STATE,
    n_jobs=-1
)

anomaly_predictions = isolation_forest.fit_predict(X_scaled)

# 1 = normal, -1 = anomaly
rfm["Anomaly"] = np.where(
    anomaly_predictions == -1,
    "Anomaly",
    "Normal"
)

# Higher anomaly score indicates more unusual behaviour
rfm["Anomaly_Score"] = -isolation_forest.decision_function(
    X_scaled
)

print("\nAnomaly distribution:")
display(rfm["Anomaly"].value_counts().reset_index())

# ------------------------------------------------
# 15. DISPLAY AT LEAST THREE ANOMALIES
# ------------------------------------------------

anomalies = (
    rfm[rfm["Anomaly"] == "Anomaly"]
    .sort_values("Anomaly_Score", ascending=False)
)

print("\nTOP 10 MOST UNUSUAL CUSTOMERS")
display(anomalies.head(10))

print("\nTHREE EXAMPLE ANOMALIES")

for index, row in anomalies.head(3).iterrows():
    print(f"""
Customer ID: {row['CustomerID']}
Recency: {row['Recency']} days
Frequency: {row['Frequency']} invoices
Monetary: {row['Monetary']:.2f}
Cluster: {row['Cluster']}
Anomaly Score: {row['Anomaly_Score']:.4f}
""")

# ------------------------------------------------
# 16. VISUALIZE ANOMALIES
# ------------------------------------------------

plt.figure(figsize=(10, 6))

sns.scatterplot(
    data=rfm,
    x="Recency",
    y="Monetary",
    hue="Anomaly",
    style="Anomaly",
    palette={
        "Normal": "steelblue",
        "Anomaly": "red"
    },
    alpha=0.7
)

plt.title("Isolation Forest - Customer Anomaly Detection")
plt.xlabel("Recency (Days)")
plt.ylabel("Monetary Value")
plt.tight_layout()
plt.show()

# ------------------------------------------------
# 17. BUSINESS INSIGHTS
# ------------------------------------------------

print("\n========================================")
print("BUSINESS INSIGHTS")
print("========================================")

total_customers = len(rfm)
total_anomalies = len(anomalies)

print(f"Total customers analysed: {total_customers}")
print(f"Number of customer segments: {best_k}")
print(
    f"Customers flagged as anomalies: {total_anomalies} "
    f"({total_anomalies / total_customers * 100:.2f}%)"
)

print("\nCUSTOMER SEGMENT RECOMMENDATIONS")

for cluster_id, row in cluster_profile.iterrows():
    print(f"""
Cluster {cluster_id}: {row['Segment_Interpretation']}
Customers: {int(row['Customer_Count'])}
Average Recency: {row['Average_Recency']:.1f} days
Average Frequency: {row['Average_Frequency']:.1f} invoices
Average Monetary: {row['Average_Monetary']:.2f}
Suggested action:
""")

    interpretation = row["Segment_Interpretation"]

    if "High-value" in interpretation or "High-spending" in interpretation:
        print("Offer loyalty rewards and personalized premium services.")
    elif "At-risk" in interpretation:
        print("Consider win-back campaigns and targeted discounts.")
    elif "Active" in interpretation or "Regular" in interpretation:
        print("Encourage repeat purchases and cross-selling.")
    else:
        print("Use targeted engagement campaigns to increase purchase frequency.")

print("""
ANOMALY DETECTION RECOMMENDATIONS

Investigate unusual customers before taking action.
Possible explanations include unusually large orders,
very frequent purchases, or long periods of inactivity.
An anomaly is not automatically fraud or a bad customer.
""")

